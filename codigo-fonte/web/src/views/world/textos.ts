/** Os dois idiomas, para o teste (textos.test.ts) conferir. */
export const TEXTOS_WORLD: Readonly<Record<Idioma, Area>> = { 'pt-BR': pt, en };

export type ChaveWorld = keyof typeof pt;
type Msg<K extends ChaveWorld> = (typeof pt)[K];
type Nomes<M> = M extends Plural ? Marcadores<M['other']> | 'n' : Marcadores<M>;
type Valores<K extends ChaveWorld, V> = Msg<K> extends Plural
  ? { readonly n: number } & { readonly [P in Exclude<Nomes<Msg<K>>, 'n'>]: V }
  : { readonly [P in Nomes<Msg<K>>]: V };
type Args<K extends ChaveWorld> = [Nomes<Msg<K>>] extends [never] ? [] : [valores: Valores<K, string | number>];

const buscar = (k: ChaveWorld): Mensagem => (TEXTOS_WORLD[idiomaAtual()] ?? pt)[k] ?? pt[k];

/** O texto do World no idioma atual da tela (como o t() de i18n/index.ts). */
export function tw<K extends ChaveWorld>(chave: K, ...valores: Args<K>): string {
  return N.montar(idiomaAtual(), buscar(chave), valores[0] as N.Valores | undefined);
}

/** A frase com pedaços de tela nos marcadores (negrito, código), na ordem de cada idioma (como o tn()). */
export function twn<K extends ChaveWorld>(chave: K, pedacos: Valores<K, ReactNode>): ReactNode {
  const l = idiomaAtual(); const m = buscar(chave);
  const p = pedacos as Readonly<Record<string, ReactNode>>;
  const texto = typeof m === 'string' ? m : N.formaDoPlural(l, m, Number(p.n ?? 0));
  const partes = N.pedacos(texto).map((x) => (typeof x === 'string' ? x : x.marca === 'n' && typeof p.n === 'number' ? N.fmtNumero(l, p.n) : p[x.marca] ?? `{${x.marca}}`));
  return createElement(Fragment, null, ...partes);
}

/** No componente: o tw(), e a troca de idioma redesenha o componente. */
export function useTw(): typeof tw { useIdioma(); return tw; }
